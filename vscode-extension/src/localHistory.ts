import fs from "node:fs";
import path from "node:path";
import type {
  HistoryMessage,
  LocalChatSession,
  LocalSessionMeta,
} from "./types";

interface LocalHistoryManifest {
  version: number;
  provider: string;
  workspace: string;
  active_session_id?: string;
  sessions: LocalSessionMeta[];
}

const MANIFEST_FILE = "manifest.json";

export function historyRoot(workspace: string, provider: string) {
  if (provider !== "opencode") {
    throw new Error(`Unsupported provider for local history: ${provider}`);
  }
  return path.join(workspace, ".opencode", "history");
}

function manifestPath(workspace: string, provider: string) {
  return path.join(historyRoot(workspace, provider), MANIFEST_FILE);
}

function readManifest(
  workspace: string,
  provider: string,
): LocalHistoryManifest {
  const filePath = manifestPath(workspace, provider);
  if (!fs.existsSync(filePath)) {
    return {
      version: 1,
      provider,
      workspace,
      active_session_id: undefined,
      sessions: [],
    };
  }
  const parsed = JSON.parse(
    fs.readFileSync(filePath, "utf8"),
  ) as Partial<LocalHistoryManifest>;
  return {
    version: parsed.version ?? 1,
    provider: parsed.provider ?? provider,
    workspace: parsed.workspace ?? workspace,
    active_session_id: parsed.active_session_id,
    sessions: Array.isArray(parsed.sessions) ? parsed.sessions : [],
  };
}

function writeManifest(
  workspace: string,
  provider: string,
  manifest: LocalHistoryManifest,
) {
  const filePath = manifestPath(workspace, provider);
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(
    filePath,
    `${JSON.stringify(manifest, null, 2)}\n`,
    "utf8",
  );
}

function sessionStem(updatedAt: string, sessionId: string) {
  const safeId = sessionId.replace(/[^A-Za-z0-9_-]/g, "_");
  const stamp = updatedAt
    .replace(/:/g, "-")
    .replace(/\./g, "-")
    .slice(0, 19);
  return `${stamp}_${safeId}`;
}

function previewFromMessages(messages: HistoryMessage[]) {
  const found =
    [...messages]
      .reverse()
      .find(
        (message) => message.role === "assistant" && message.content.trim(),
      ) ??
    [...messages]
      .reverse()
      .find((message) => message.role === "user" && message.content.trim());
  if (!found) return undefined;
  const trimmed = found.content.trim().replace(/\n/g, " ");
  const chars = Array.from(trimmed);
  return chars.length > 120
    ? `${chars.slice(0, 120).join("")}…`
    : trimmed;
}

function titleFromMessages(messages: HistoryMessage[], sessionId: string) {
  const found = messages.find(
    (message) => message.role === "user" && message.content.trim(),
  );
  if (!found) return sessionId;
  const trimmed = found.content.trim().replace(/\n/g, " ");
  const chars = Array.from(trimmed);
  return chars.length > 48
    ? `${chars.slice(0, 48).join("")}…`
    : trimmed;
}

function roleLabel(role: string, toolName?: string) {
  if (role === "user") return "User";
  if (role === "assistant") return "Assistant";
  if (role === "tool") return `Tool · ${toolName || "unknown"}`;
  return role;
}

function renderMarkdown(session: LocalChatSession) {
  const lines = [
    "<!-- Generated by xcoder -->",
    "",
    `# ${session.title}`,
    "",
    `<!-- Session ${session.id} (${session.updated_at}) -->`,
    "",
  ];
  for (const message of session.messages) {
    if (!message.content.trim()) continue;
    lines.push(`_**${roleLabel(message.role, message.tool_name)}**_`);
    lines.push("");
    lines.push(message.content);
    lines.push("");
    lines.push("---");
    lines.push("");
  }
  return lines.join("\n");
}

export function saveLocalSession(
  workspace: string,
  provider: string,
  session: LocalChatSession,
  setActive = true,
): LocalSessionMeta {
  const dir = historyRoot(workspace, provider);
  fs.mkdirSync(dir, { recursive: true });
  const manifest = readManifest(workspace, provider);

  const title = session.title.trim()
    ? session.title
    : titleFromMessages(session.messages, session.id);
  const preview = previewFromMessages(session.messages);
  const stem = sessionStem(session.updated_at, session.id);
  const markdownFile = `${stem}.md`;
  const dataFile = `${stem}.json`;
  const persisted: LocalChatSession = {
    ...session,
    title,
  };

  fs.writeFileSync(path.join(dir, markdownFile), renderMarkdown(persisted), "utf8");
  fs.writeFileSync(
    path.join(dir, dataFile),
    JSON.stringify(persisted, null, 2),
    "utf8",
  );

  const meta: LocalSessionMeta = {
    id: persisted.id,
    title,
    updated_at: persisted.updated_at,
    markdown_file: markdownFile,
    data_file: dataFile,
    preview,
  };

  const existing = manifest.sessions.find((item) => item.id === meta.id);
  if (existing) {
    if (
      existing.markdown_file !== markdownFile &&
      fs.existsSync(path.join(dir, existing.markdown_file))
    ) {
      fs.rmSync(path.join(dir, existing.markdown_file), { force: true });
    }
    if (
      existing.data_file !== dataFile &&
      fs.existsSync(path.join(dir, existing.data_file))
    ) {
      fs.rmSync(path.join(dir, existing.data_file), { force: true });
    }
    Object.assign(existing, meta);
  } else {
    manifest.sessions.unshift(meta);
  }

  manifest.sessions.sort((left, right) =>
    right.updated_at.localeCompare(left.updated_at),
  );
  if (setActive) manifest.active_session_id = persisted.id;
  manifest.workspace = workspace;
  manifest.provider = provider;
  writeManifest(workspace, provider, manifest);
  return meta;
}

export function listLocalSessions(
  workspace: string,
  provider: string,
): LocalSessionMeta[] {
  return readManifest(workspace, provider).sessions;
}

export function loadLocalSession(
  workspace: string,
  provider: string,
  sessionId: string,
): LocalChatSession | null {
  const manifest = readManifest(workspace, provider);
  const meta = manifest.sessions.find((item) => item.id === sessionId);
  if (!meta) return null;
  const filePath = path.join(
    historyRoot(workspace, provider),
    meta.data_file,
  );
  if (!fs.existsSync(filePath)) return null;
  return JSON.parse(fs.readFileSync(filePath, "utf8")) as LocalChatSession;
}

export function getActiveLocalSession(
  workspace: string,
  provider: string,
) {
  return readManifest(workspace, provider).active_session_id ?? null;
}

export function setActiveLocalSession(
  workspace: string,
  provider: string,
  sessionId: string | null,
) {
  const manifest = readManifest(workspace, provider);
  manifest.active_session_id = sessionId ?? undefined;
  writeManifest(workspace, provider, manifest);
}

export function deleteLocalSession(
  workspace: string,
  provider: string,
  sessionId: string,
) {
  const manifest = readManifest(workspace, provider);
  const index = manifest.sessions.findIndex((item) => item.id === sessionId);
  if (index < 0) return;
  const [meta] = manifest.sessions.splice(index, 1);
  const dir = historyRoot(workspace, provider);
  fs.rmSync(path.join(dir, meta.markdown_file), { force: true });
  fs.rmSync(path.join(dir, meta.data_file), { force: true });
  if (manifest.active_session_id === sessionId) {
    manifest.active_session_id = manifest.sessions[0]?.id;
  }
  writeManifest(workspace, provider, manifest);
}
